    static func variants(for phrase: String, maxCount: Int = 32) -> [String] {
        let tokens = phrase
            .lowercased()
            .replacingOccurrences(of: "ё", with: "е")
            .split(separator: " ")
            .map(String.init)

        guard !tokens.isEmpty, tokens.count <= 4 else { return [phrase] }

        let choices = tokens.map { token in
            forms[token] ?? [token]
        }

        var results: [String] = []
        build(choices: choices, index: 0, current: [], results: &results, maxCount: maxCount)

        var ordered = [phrase]
        for result in results where !ordered.contains(result) {
            ordered.append(result)
        }
        return Array(ordered.prefix(maxCount))
    }

    private static func build(choices: [[String]], index: Int, current: [String], results: inout [String], maxCount: Int) {
        guard results.count < maxCount else { return }
        if index == choices.count {
            results.append(current.joined(separator: " "))
            return
        }
        for choice in choices[index] {
            build(choices: choices, index: index + 1, current: current + [choice], results: &results, maxCount: maxCount)
            if results.count >= maxCount { return }
        }
    }
